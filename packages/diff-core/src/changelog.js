import { SEVERITY } from './changes.js';

const HEADINGS = {
  [SEVERITY.BREAKING]: '### 💥 Breaking changes',
  [SEVERITY.ADDITIVE]: '### ✨ Additive changes',
  [SEVERITY.COSMETIC]: '### 🧹 Cosmetic changes',
};

const GROUP_ORDER = [SEVERITY.BREAKING, SEVERITY.ADDITIVE, SEVERITY.COSMETIC];

/**
 * Render a paste-ready Markdown changelog.
 * `meta`: { title, fromVersion, toVersion, level }
 */
export function renderChangelog(changes, meta = {}) {
  const { title = 'API changelog', fromVersion, toVersion, level } = meta;
  const lines = [`## ${title}`, ''];

  if (fromVersion || toVersion) {
    const label = [fromVersion ?? 'previous', toVersion ?? 'next'].filter(Boolean).join(' → ');
    lines.push(`**Version:** ${label}${level ? ` (${level} bump)` : ''}`, '');
  }

  if (changes.length === 0) {
    lines.push('No changes detected.');
    return lines.join('\n');
  }

  for (const severity of GROUP_ORDER) {
    const group = changes.filter((change) => change.severity === severity);
    if (group.length === 0) continue;
    lines.push(HEADINGS[severity], '');
    for (const change of group) {
      lines.push(`- **${change.location}** — ${change.message}`);
    }
    lines.push('');
  }

  const counts = GROUP_ORDER.map((severity) => ({
    severity,
    count: changes.filter((change) => change.severity === severity).length,
  })).filter((entry) => entry.count > 0);

  lines.push(
    `<sub>${counts.map((entry) => `${entry.count} ${entry.severity}`).join(' · ')} · generated by SpecDrift</sub>`,
  );

  return lines.join('\n');
}
